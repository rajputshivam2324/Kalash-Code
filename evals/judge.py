"""LLM-as-a-Judge Evaluation Framework for Kalash CLI.

Evaluates generated coding agent artifacts (code, documentation, architectures)
against reference standards or rubrics across multiple dimensions:
1. Functional Completeness (all requirements & chapters present)
2. Algorithmic Correctness & Invariants (optimal complexity, edge cases)
3. Code Quality & Modern Python Style (types, docstrings, testability)
4. Developer Experience & Presentation (clean structure, tables, readability)

Provides both live LLM judging (via ModelGateway/Groq/OpenAI/Gemini) and deterministic
offline rubric grading for CI environments.
"""

from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from evals.harness import SuiteReport, TaskResult

logger = logging.getLogger(__name__)


@dataclass
class DimensionScore:
    """Score for an individual rubric dimension."""

    name: str
    score: float  # 0.0 to 10.0
    weight: float
    reasoning: str
    findings: list[str] = field(default_factory=list)


@dataclass
class JudgeScorecard:
    """Comprehensive evaluation scorecard generated by the judge."""

    candidate_name: str
    dimensions: list[DimensionScore]
    overall_score: float  # Weighted 0.0 to 10.0 (>= 8.0 is PASS)
    passed: bool
    summary: str
    strengths: list[str] = field(default_factory=list)
    areas_for_improvement: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "candidate": self.candidate_name,
            "overall_score": round(self.overall_score, 2),
            "passed": self.passed,
            "summary": self.summary,
            "dimensions": [
                {
                    "name": d.name,
                    "score": round(d.score, 1),
                    "weight": d.weight,
                    "reasoning": d.reasoning,
                    "findings": d.findings,
                }
                for d in self.dimensions
            ],
            "strengths": self.strengths,
            "improvements": self.areas_for_improvement,
        }


def evaluate_content_deterministic(
    title: str,
    content: str,
    required_keywords: list[str],
    required_code_patterns: list[str],
    is_code_file: bool = True,
) -> JudgeScorecard:
    """Deterministic offline evaluator for CI test suites without API dependencies."""
    findings_comp = []
    findings_corr = []
    findings_qual = []
    findings_dx = []

    # 1. Completeness check
    missing_kw = [kw for kw in required_keywords if kw.lower() not in content.lower()]
    if not missing_kw:
        comp_score = 10.0
        findings_comp.append(f"All {len(required_keywords)} required concepts present.")
    else:
        ratio = (len(required_keywords) - len(missing_kw)) / max(len(required_keywords), 1)
        comp_score = round(ratio * 10.0, 1)
        findings_comp.append(f"Missing {len(missing_kw)} concepts: {', '.join(missing_kw[:3])}")

    # 2. Correctness check (code patterns)
    matched_pat = 0
    for pat in required_code_patterns:
        if re.search(pat, content, re.MULTILINE | re.IGNORECASE):
            matched_pat += 1
    corr_score = round((matched_pat / max(len(required_code_patterns), 1)) * 10.0, 1)
    findings_corr.append(f"Matched {matched_pat}/{len(required_code_patterns)} algorithmic patterns.")

    # Check for overflow safety: low + (high - low) // 2
    if is_code_file:
        if "low + (high - low)" in content or "low + ((high - low)" in content or "low + (high-low)" in content or "lo + (hi - lo)" in content:
            findings_corr.append("Protected against integer overflow.")
        else:
            corr_score = max(0.0, corr_score - 1.0)
            findings_corr.append("Missing explicit integer overflow safe midpoint formula.")

    # 3. Code quality check (Python blocks, type hints, comments)
    has_code_blocks = "```python" in content or "```py" in content
    has_type_hints = bool(re.search(r"def\s+\w+\(.*:\s*\w+.*\)\s*->", content))
    has_docstrings = '"""' in content or "'''" in content

    qual_score = 6.0
    if has_code_blocks:
        qual_score += 2.0
        findings_qual.append("Contains syntax-highlighted Python code blocks.")
    if has_type_hints:
        qual_score += 1.0
        findings_qual.append("Uses modern Python type hints.")
    if has_docstrings:
        qual_score += 1.0
        findings_qual.append("Includes docstrings / explanatory comments.")

    # 4. DX & Formatting
    has_headers = bool(re.search(r"^#{1,3}\s+", content, re.MULTILINE))
    has_tables = "|" in content and "---" in content
    no_emojis = not bool(re.search(r"[\U00010000-\U0010ffff]", content))

    dx_score = 6.0
    if has_headers:
        dx_score += 2.0
        findings_dx.append("Hierarchical header structure.")
    if has_tables:
        dx_score += 1.0
        findings_dx.append("Contains structured summary tables.")
    if no_emojis:
        dx_score += 1.0
        findings_dx.append("Clean developer typography without emoji clutter.")

    dims = [
        DimensionScore("completeness", comp_score, 0.35, "Evaluated required topic coverage.", findings_comp),
        DimensionScore("correctness", corr_score, 0.35, "Evaluated algorithmic formulas and invariants.", findings_corr),
        DimensionScore("code_quality", min(10.0, qual_score), 0.15, "Evaluated code structure and type hints.", findings_qual),
        DimensionScore("developer_experience", min(10.0, dx_score), 0.15, "Evaluated markdown layout and readability.", findings_dx),
    ]

    overall = sum(d.score * d.weight for d in dims)
    passed = overall >= 7.5 and comp_score >= 6.0 and corr_score >= 6.0

    return JudgeScorecard(
        candidate_name=title,
        dimensions=dims,
        overall_score=overall,
        passed=passed,
        summary=f"{title}: Score {overall:.1f}/10 ({'PASSED' if passed else 'FAILED'})",
        strengths=[f for d in dims for f in d.findings if "All" in f or "Protected" in f or "Clean" in f],
        areas_for_improvement=[f for d in dims for f in d.findings if "Missing" in f],
    )


async def run_binary_search_notes_judge(directory: Path) -> SuiteReport:
    """Evaluate all binary search note artifacts generated in a directory."""
    results: list[TaskResult] = []

    # Chapter 1: Fundamentals
    ch1 = directory / "01_fundamentals.md"
    if ch1.exists():
        scorecard = evaluate_content_deterministic(
            "01_fundamentals.md",
            ch1.read_text(),
            required_keywords=["monotonic", "invariant", "template", "overflow"],
            required_code_patterns=[r"while\s+\w+\s*<=?\s*\w+", r"mid\s*=\s*\w+\s*\+\s*\(\w+\s*-\s*\w+\)"],
        )
        results.append(TaskResult(
            name="chapter_1_fundamentals",
            passed=scorecard.passed,
            detail=f"Score {scorecard.overall_score:.1f}/10 — {scorecard.summary}",
        ))
    else:
        results.append(TaskResult(name="chapter_1_fundamentals", passed=False, detail="File 01_fundamentals.md missing."))

    # Chapter 2: Lower/Upper Bounds
    ch2 = directory / "02_lower_upper_bounds.md"
    if not ch2.exists():
        ch2 = directory / "02_lower_upper_bound.md"

    if ch2.exists():
        scorecard = evaluate_content_deterministic(
            "02_lower_upper_bounds.md",
            ch2.read_text(),
            required_keywords=["lower_bound", "upper_bound", "first", "last"],
            required_code_patterns=[r"lower_bound|first_occurrence", r"upper_bound|last_occurrence"],
        )
        results.append(TaskResult(
            name="chapter_2_lower_upper_bounds",
            passed=scorecard.passed,
            detail=f"Score {scorecard.overall_score:.1f}/10 — {scorecard.summary}",
        ))
    else:
        results.append(TaskResult(name="chapter_2_lower_upper_bounds", passed=False, detail="File 02_lower_upper_bounds.md missing."))

    # Chapter 3: Search on Answer
    ch3 = directory / "03_search_on_answer.md"
    if not ch3.exists():
        ch3 = directory / "03_binary_search_on_answer.md"

    if ch3.exists():
        scorecard = evaluate_content_deterministic(
            "03_search_on_answer.md",
            ch3.read_text(),
            required_keywords=["minimize", "maximize", "predicate", "koko", "bananas"],
            required_code_patterns=[r"def\s+\w+", r"while\s+\w+\s*<=?\s*\w+"],
        )
        results.append(TaskResult(
            name="chapter_3_search_on_answer",
            passed=scorecard.passed,
            detail=f"Score {scorecard.overall_score:.1f}/10 — {scorecard.summary}",
        ))
    else:
        results.append(TaskResult(name="chapter_3_search_on_answer", passed=False, detail="File 03_search_on_answer.md missing."))

    # Chapter 4: Rotated & Peaks
    ch4 = directory / "04_rotated_and_peaks.md"
    if not ch4.exists():
        ch4 = directory / "04_rotated_arrays_and_peaks.md"

    if ch4.exists():
        scorecard = evaluate_content_deterministic(
            "04_rotated_and_peaks.md",
            ch4.read_text(),
            required_keywords=["rotated", "pivot", "peak", "sorted"],
            required_code_patterns=[r"nums\[mid\]\s*>\s*nums\[\w+\]|nums\[mid\]\s*<\s*nums\[mid\s*\+\s*1\]", r"def\s+\w+"],
        )
        results.append(TaskResult(
            name="chapter_4_rotated_and_peaks",
            passed=scorecard.passed,
            detail=f"Score {scorecard.overall_score:.1f}/10 — {scorecard.summary}",
        ))
    else:
        results.append(TaskResult(name="chapter_4_rotated_and_peaks", passed=False, detail="File 04_rotated_and_peaks.md missing."))

    # Chapter 5: 2D Matrix
    ch5 = directory / "05_2d_matrix_search.md"
    if not ch5.exists():
        ch5 = directory / "05_2d_matrix.md"

    if ch5.exists():
        scorecard = evaluate_content_deterministic(
            "05_2d_matrix_search.md",
            ch5.read_text(),
            required_keywords=["matrix", "flatten|mapping|coordinate", "staircase|stair", "row", "col"],
            required_code_patterns=[r"mid\s*//\s*\w+|mid\s*%\s*\w+", r"def\s+\w+"],
        )
        results.append(TaskResult(
            name="chapter_5_2d_matrix",
            passed=scorecard.passed,
            detail=f"Score {scorecard.overall_score:.1f}/10 — {scorecard.summary}",
        ))
    else:
        results.append(TaskResult(name="chapter_5_2d_matrix", passed=False, detail="File 05_2d_matrix.md missing."))

    # README Master Index
    readme = directory / "README.md"
    if readme.exists():
        scorecard = evaluate_content_deterministic(
            "README.md",
            readme.read_text(),
            required_keywords=["binary search", "fundamentals|chapter", "bounds|bound", "answer", "matrix"],
            required_code_patterns=[r"\|", r"01_|chapter|basic"],
            is_code_file=False,
        )
        results.append(TaskResult(
            name="master_readme_index",
            passed=scorecard.passed,
            detail=f"Score {scorecard.overall_score:.1f}/10 — {scorecard.summary}",
        ))
    else:
        results.append(TaskResult(name="master_readme_index", passed=False, detail="File README.md missing."))

    return SuiteReport("llm_judge_binary_search", results)
